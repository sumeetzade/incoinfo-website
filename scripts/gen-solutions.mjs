// Generates the 12 solution pages, the solutions hub, sitemap.xml and robots.txt.
// Usage: node scripts/gen-solutions.mjs
import fs from 'node:fs'
import path from 'node:path'
import { segments, solutions } from '../src/data/solutions.mjs'

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const write = (file, html) => {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, html.replace(/\n{3,}/g, '\n\n'))
  console.log('wrote', file)
}
const seg = (id) => segments.find((s) => s.id === id)
const banner = '<!-- GENERATED by scripts/gen-solutions.mjs from src/data/solutions.mjs. Do not edit by hand. -->'

const head = ({ title, description, path: p, ld }) => `<!doctype html>
${banner}
<html lang="en-IN">
  <head>
    <!-- @include head title="${esc(title)}" description="${esc(description)}" path="${p}" -->${ld ? `\n    <script type="application/ld+json">${JSON.stringify(ld)}</script>` : ''}
  </head>
  <body>
    <!-- @include nav -->
    <main id="main">`

const foot = `    </main>
    <!-- @include final-cta -->
    <!-- @include footer -->
  </body>
</html>
`

const crumbsLd = (items) => ({
  '@context': 'https://schema.org',
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, url], i) => ({ '@type': 'ListItem', position: i + 1, name, item: `%SITE_URL%${url}` })),
})

function solutionPage(s) {
  const g = seg(s.segment)
  const related = solutions.filter((x) => x.segment === s.segment && x.slug !== s.slug)
  const url = `/solutions/${s.slug}/`

  const compare = s.compare
    ? `
          <div class="compare" data-reveal>
            <h3>How the report compares</h3>
            <div class="table-scroll">
              <table class="fin-table compare-table">
                <thead><tr>${s.compare.head.map((h, i) => `<th scope="col"${i === 2 ? ' class="is-us"' : ''}>${esc(h)}</th>`).join('')}</tr></thead>
                <tbody>
${s.compare.rows.map((r) => `                  <tr><th scope="row">${esc(r[0])}</th><td>${esc(r[1])}</td><td class="is-us">${esc(r[2])}</td></tr>`).join('\n')}
                </tbody>
              </table>
            </div>
          </div>`
    : ''

  const benchmark = s.benchmark
    ? `
          <div class="compare" data-reveal>
            <h3>Example peer benchmark</h3>
            <p class="muted">Illustrative figures from three sample companies in one sector, FY25.</p>
            <div class="table-scroll">
              <table class="fin-table">
                <thead><tr><th scope="col">Metric</th><th scope="col">Your company</th><th scope="col">Competitor A</th><th scope="col">Competitor B</th></tr></thead>
                <tbody>
                  <tr><th scope="row">Annual revenue</th><td>₹150.0 Cr</td><td>₹210.5 Cr</td><td>₹88.2 Cr</td></tr>
                  <tr><th scope="row">EBITDA margin</th><td>18.4%</td><td>14.2%</td><td>21.0%</td></tr>
                  <tr><th scope="row">Debt to equity</th><td>0.35</td><td>1.12</td><td>0.08</td></tr>
                  <tr><th scope="row">Open charges</th><td>₹12.5 Cr</td><td>₹68.0 Cr</td><td>₹2.1 Cr</td></tr>
                  <tr><th scope="row">Filing status</th><td><span class="badge badge-success">Up to date</span></td><td><span class="badge badge-success">Up to date</span></td><td><span class="badge badge-warn">30 days late</span></td></tr>
                </tbody>
              </table>
            </div>
          </div>`
    : ''

  const example = s.example
    ? `
      <section class="section section-tint" aria-labelledby="example-title">
        <div class="container-x">
          <figure class="example card" data-reveal>
            <p class="example-label" id="example-title">{{icon:file-check-2}} Example order</p>
            <blockquote>${esc(s.example.text)}</blockquote>
            <figcaption>${esc(s.example.who)}</figcaption>
          </figure>
        </div>
      </section>`
    : ''

  return `${head({
    title: `${s.title} | IncoInfo`,
    description: s.subtitle,
    path: url,
    ld: crumbsLd([['Home', '/'], ['Solutions', '/solutions/'], [s.name, url]]),
  })}
      <section class="page-hero" aria-labelledby="page-title">
        <div class="container-x page-hero-grid">
          <div>
            <nav class="crumbs" aria-label="Breadcrumb">
              <ol><li><a href="/solutions/">Solutions</a></li><li><a href="/solutions/#${g.id}">${esc(g.name)}</a></li><li aria-current="page">${esc(s.name)}</li></ol>
            </nav>
            <h1 id="page-title">${esc(s.title)}</h1>
            <p class="lede">${esc(s.subtitle)}</p>
            <p class="audience">{{icon:users}}<span>For ${esc(s.audience.charAt(0).toLowerCase() + s.audience.slice(1))}</span></p>
            <div class="page-hero-ctas">
              <a class="btn btn-primary btn-lg" href="%PORTAL_URL%/" data-magnetic>Open the demo {{icon:arrow-right}}</a>
              <a class="btn btn-secondary btn-lg" href="/pricing/">See pricing</a>
            </div>
          </div>
          <aside class="hero-aside card-float" aria-label="What your report includes">
            <p class="hero-aside-title"><span class="icon-tile">{{icon:${s.icon}}}</span>In every report for this team</p>
            <ul class="checklist">
${s.deliverables.map(([t]) => `              <li>{{icon:check}}<span>${esc(t)}</span></li>`).join('\n')}
              <li>{{icon:refresh-cw}}<span>New filings added for 12 months</span></li>
            </ul>
          </aside>
        </div>
      </section>

      <section class="section" aria-labelledby="pains-title">
        <div class="container-x">
          <div class="section-head" data-reveal>
            <h2 id="pains-title">What gets in the way today</h2>
          </div>
          <div class="pains" data-reveal-stagger>
${s.pains.map(([t, d]) => `            <article class="pain">
              <span class="pain-icon">{{icon:circle-alert}}</span>
              <h3>${esc(t)}</h3>
              <p>${esc(d)}</p>
            </article>`).join('\n')}
          </div>
        </div>
      </section>

      <section class="section section-tint" aria-labelledby="flow-title">
        <div class="container-x">
          <div class="section-head" data-reveal>
            <h2 id="flow-title">How IncoInfo fits your workflow</h2>
          </div>
          <ol class="steps steps-3" data-steps>
${s.steps.map(([t, d], i) => `            <li class="step">
              <span class="step-marker"><span class="num">${i + 1}</span></span>
              <h3>${esc(t)}</h3>
              <p>${esc(d)}</p>
            </li>`).join('\n')}
          </ol>
        </div>
      </section>

      <section class="section" aria-labelledby="deliver-title">
        <div class="container-x">
          <div class="section-head" data-reveal>
            <h2 id="deliver-title">What your report includes</h2>
            <p class="lede">Every report also contains the standard sections: financials, directors, shareholding, charges, compliance and related companies.</p>
          </div>
          <div class="deliverables" data-reveal-stagger>
${s.deliverables.map(([t, d]) => `            <article class="deliverable">
              <span class="icon-tile">{{icon:file-check-2}}</span>
              <div><h3>${esc(t)}</h3><p>${esc(d)}</p></div>
            </article>`).join('\n')}
          </div>${compare}${benchmark}
        </div>
      </section>
${example}
      <section class="section related" aria-labelledby="related-title">
        <div class="container-x">
          <h2 id="related-title" class="related-title">More for ${esc(g.long.toLowerCase())}</h2>
          <div class="related-grid">
${related.map((r) => `            <a class="related-card card card-hover" href="/solutions/${r.slug}/">
              <span class="icon-tile">{{icon:${r.icon}}}</span>
              <span><strong>${esc(r.name)}</strong><small>${esc(r.summary)}</small></span>
              {{icon:arrow-right|related-arrow}}
            </a>`).join('\n')}
          </div>
        </div>
      </section>
${foot}`
}

function hubPage() {
  return `${head({
    title: 'Solutions by team | IncoInfo',
    description: 'How lenders, investors, corporate teams and professional firms use IncoInfo company reports built from official filings.',
    path: '/solutions/',
    ld: crumbsLd([['Home', '/'], ['Solutions', '/solutions/']]),
  })}
      <section class="page-hero page-hero-simple" aria-labelledby="page-title">
        <div class="container-x">
          <h1 id="page-title">Company data for the way your team works</h1>
          <p class="lede">Twelve teams, four groups. Each page shows the problems that team runs into, the workflow, and the report sections it relies on most.</p>
        </div>
      </section>
${segments.map((g, gi) => `
      <section class="section${gi % 2 ? ' section-tint' : ''} hub-group" id="${g.id}" aria-labelledby="g-${g.id}">
        <div class="container-x hub-grid">
          <div class="hub-head" data-reveal>
            <span class="icon-tile">{{icon:${g.icon}}}</span>
            <h2 id="g-${g.id}">${esc(g.long.charAt(0).toUpperCase() + g.long.slice(1))}</h2>
          </div>
          <div class="hub-cards" data-reveal-stagger>
${solutions.filter((s) => s.segment === g.id).map((s) => `            <a class="hub-card card card-hover" href="/solutions/${s.slug}/" data-tilt>
              <span class="icon-tile">{{icon:${s.icon}}}</span>
              <h3>${esc(s.name)}</h3>
              <p>${esc(s.summary)}</p>
              <span class="hub-more">See the workflow {{icon:arrow-right}}</span>
            </a>`).join('\n')}
          </div>
        </div>
      </section>`).join('\n')}
${foot}`
}

for (const s of solutions) write(`solutions/${s.slug}/index.html`, solutionPage(s))
write('solutions/index.html', hubPage())

// sitemap + robots (static pages listed here; keep in sync when adding pages)
const site = (fs.readFileSync('.env', 'utf8').match(/VITE_SITE_URL=(.*)/) || [])[1]?.trim() || 'https://www.incoinfo.com'
const pages = ['/', '/solutions/', ...solutions.map((s) => `/solutions/${s.slug}/`), '/pricing/', '/database/', '/macro-view/', '/data-standards/', '/company/', '/legal/privacy/', '/legal/terms/', '/legal/refunds/', '/legal/disclaimer/']
write('public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((p) => `  <url><loc>${site}${p}</loc></url>`).join('\n')}
</urlset>
`)
write('public/robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`)
